router = APIRouter(prefix="/auth", tags=["authentication"])


@router.post("/register")
async def register_user(
    user_data: UserCreate, 
    response: Response,
    auth_service: AuthService = Depends(get_auth_service),
    db = Depends(get_database)
):
    """Register a new user with secure httpOnly cookie authentication"""
    
    # Check if user already exists
    existing_user = await db.users.find_one({"email": user_data.email})
    if existing_user:
        raise HTTPException(status_code=400, detail="Email already registered")
    
    # Hash password and create user
    password_hash = auth_service.hash_password(user_data.password)
    user = User(
        **user_data.dict(exclude={'password'}),
        password_hash=password_hash
    )
    
    # Save to database
    await db.users.insert_one(user.dict())
    
    # Create JWT token
    token = auth_service.create_jwt_token(user.user_id, user.email)
    
    # Set secure httpOnly cookie
    auth_service.set_secure_cookie(response, token)
    
    return {
        "message": "User registered successfully",
        "token": token,  # For backward compatibility with Bearer token auth
        "user": {
            "user_id": user.user_id,
            "full_name": user.full_name,
            "email": user.email,
            "exam_type": user.exam_type
        }
    }


@router.post("/login")
async def login_user(
    login_data: UserLogin, 
    response: Response,
    auth_service: AuthService = Depends(get_auth_service),
    db = Depends(get_database)
):
    """Login user with secure httpOnly cookie authentication"""
    
    # Find user
    user_doc = await db.users.find_one({"email": login_data.email})
    if not user_doc:
        raise HTTPException(status_code=401, detail="Invalid email or password")
    
    user = User(**user_doc)
    
    # Verify password
    if not auth_service.verify_password(login_data.password, user.password_hash):
        raise HTTPException(status_code=401, detail="Invalid email or password")
    
    # Create JWT token
    token = auth_service.create_jwt_token(user.user_id, user.email)
    
    # Set secure httpOnly cookie
    auth_service.set_secure_cookie(response, token)
    
    return {
        "message": "Login successful",
        "token": token,  # For backward compatibility with Bearer token auth
        "user": {
            "user_id": user.user_id,
            "full_name": user.full_name,
            "email": user.email,
            "exam_type": user.exam_type,
            "subscription_type": user.subscription_type
        }
    }


@router.post("/logout")
async def logout_user(
    response: Response,
    request: Request,
    auth_service: AuthService = Depends(get_auth_service),
    db = Depends(get_database)
):
    """Logout user by clearing the authentication cookie and session"""
    from datetime import datetime, timezone
    
    # Get session token
    session_token = request.cookies.get("dhruv_ai_session") or request.cookies.get("dhruv_ai_auth")
    
    # Clear session from database if exists
    if session_token:
        await db.users.update_many(
            {"session_token": session_token},
            {"$set": {
                "session_token": None,
                "session_expiry": None
            }}
        )
    
    # Clear cookies
    auth_service.clear_secure_cookie(response)
    is_production = os.environ.get('ENVIRONMENT', 'development') == 'production'
    response.delete_cookie(
        key="dhruv_ai_session",
        httponly=True,
        secure=is_production,
        samesite="lax",
        path="/"
    )
    
    return {"message": "Logout successful"}


@router.get("/csrf-token")
async def get_csrf_token(request: Request):
    """Get CSRF token for secure form submissions"""
    # The CSRF token is automatically generated by the middleware
    # and available in the request context
    csrf_token = request.scope.get('csrf_token', '')
    return {"csrf_token": csrf_token}


@router.post("/google/session")
async def exchange_google_session(
    request: Request,
    response: Response,
    db = Depends(get_database)
):
    """
    Exchange Emergent session_id for user data
    Acts as a proxy to avoid CORS issues
    """
    import aiohttp
    
    try:
        body = await request.json()
        session_id = body.get('session_id')
        
        if not session_id:
            raise HTTPException(status_code=400, detail="session_id is required")
        
        # Call Emergent API
        async with aiohttp.ClientSession() as session:
            async with session.get(
                'https://demobackend.emergentagent.com/auth/v1/env/oauth/session-data',
                headers={'X-Session-ID': session_id}
            ) as resp:
                if resp.status != 200:
                    error_text = await resp.text()
                    raise HTTPException(
                        status_code=resp.status,
                        detail=f"Emergent API error: {error_text}"
                    )
                
                session_data = await resp.json()
                
                # Now process the login
                result = await process_google_login(session_data, db)
                
                # Set httpOnly cookie with session token
                is_production = os.environ.get('ENVIRONMENT', 'development') == 'production'
                response.set_cookie(
                    key="dhruv_ai_session",
                    value=session_data['session_token'],
                    max_age=7 * 24 * 60 * 60,  # 7 days
                    httponly=True,
                    secure=is_production,
                    samesite="lax",
                    path="/"
                )
                
                return result
                
    except HTTPException:
        raise
    except Exception as e:
        raise HTTPException(
            status_code=500,
            detail=f"Session exchange failed: {str(e)}"
        )


async def process_google_login(session_data: dict, db):
    """Helper function to process Google login"""
    from models.core import User
    from datetime import datetime, timezone, timedelta
    
    # Check if user exists by Google ID or email
    existing_user = await db.users.find_one({
        "$or": [
            {"google_id": session_data['id']},
            {"email": session_data['email']}
        ]
    })
    
    if existing_user:
        # Update session token and expiry
        session_expiry = datetime.now(timezone.utc) + timedelta(days=7)
        await db.users.update_one(
            {"user_id": existing_user["user_id"]},
            {"$set": {
                "session_token": session_data['session_token'],
                "session_expiry": session_expiry,
                "google_id": session_data['id'],
                "photo_url": session_data['picture'],
                "auth_provider": "google"
            }}
        )
        user = User(**existing_user)
        user.session_token = session_data['session_token']
        user.session_expiry = session_expiry
        user.google_id = session_data['id']
        user.photo_url = session_data['picture']
    else:
        # Create new user
        session_expiry = datetime.now(timezone.utc) + timedelta(days=7)
        user = User(
            full_name=session_data['name'],
            email=session_data['email'],
            google_id=session_data['id'],
            photo_url=session_data['picture'],
            auth_provider="google",
            session_token=session_data['session_token'],
            session_expiry=session_expiry,
            profile_completed=False
        )
        await db.users.insert_one(user.dict())
    
    return {
        "message": "Authentication successful",
        "session_token": session_data['session_token'],
        "user": {
            "user_id": user.user_id,
            "full_name": user.full_name,
            "email": user.email,
            "photo_url": user.photo_url,
            "exam_type": user.exam_type,
            "profile_completed": user.profile_completed,
            "subscription_type": user.subscription_type
        }
    }


